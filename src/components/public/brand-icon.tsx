/** An icon only for recognised sites. A generic fallback on every other link is just noise. */
export function BrandIcon({ url, size = 18 }: { url?: string; size?: number }) {
  const d = PATHS[brandOf(url)];
  if (!d) return null;
  return (
    <svg viewBox="0 0 24 24" width={size} height={size} fill="currentColor" aria-hidden="true">
      <path d={d} />
    </svg>
  );
}

export function HoverArrow({ size = 16 }: { size?: number }) {
  return <ArrowUpRight width={size} height={size} strokeWidth={2.5} aria-hidden="true" />;
}
