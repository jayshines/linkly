type Brand = "github" | "x" | "youtube" | "instagram" | "linkedin" | "mail" | "web";

const HOSTS: [RegExp, Brand][] = [
  [/(^|\.)github\.com$/, "github"],
  [/(^|\.)(x|twitter)\.com$/, "x"],
  [/(^|\.)(youtube\.com|youtu\.be)$/, "youtube"],
  [/(^|\.)instagram\.com$/, "instagram"],
  [/(^|\.)linkedin\.com$/, "linkedin"],
];

/** Picks a brand from the link's host. No network requests: icons are inline. */
export function brandOf(url?: string): Brand {
  if (!url) return "web";
  try {
    const host = new URL(url).hostname.toLowerCase();
    return HOSTS.find(([re]) => re.test(host))?.[1] ?? "web";
  } catch {
    return "web";
  }
}

